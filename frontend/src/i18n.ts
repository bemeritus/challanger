const dict: Record<Lang, Dict> = { uz, en, ru };

type Vars = Record<string, string | number>;

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function t(key: string, vars?: Vars): string {
  const s = dict[current][key] ?? uz[key] ?? key;
  return interpolate(s, vars);
}

/// Prioritet yorlig'i (joriy tilda)
export function priorityLabel(p: number): string {
  return t(`priority.${p}`);
}

/// Takrorlanish yorlig'i (joriy tilda), null bo'lsa bo'sh
export function recurrenceLabel(r: string | null | undefined): string {
  return r ? t(`recur.${r}`) : "";
}

/// Oy nomi (0–11)
export function monthName(m: number): string {
  return t(`month.${m}`);
}

/// Hafta kunlari (qisqa, dushanbadan) — joriy tilda
export function weekdayShorts(): string[] {
  return [0, 1, 2, 3, 4, 5, 6].map((i) => t(`wd.${i}`));
}

/// Komponentni joriy tilga obuna qiladi va `t` funksiyasini qaytaradi.
export function useT(): typeof t {
  const [, force] = useReducer((x) => x + 1, 0);
  useEffect(() => {
    const fn = () => force();
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  }, []);
  return t;
}
